export type TranslationKey = keyof typeof messages.ar;

export function translate(language: Language, key: TranslationKey): string {
  return messages[language][key];
}

export function localizedCategoryName(category: Category | undefined, language: Language): string {
  if (!category) return translate(language, "department");
  return language === "en" && category.name_en ? category.name_en : category.name;
}

export function localizedCategoryDescription(category: Category | undefined, language: Language): string {
  if (!category) return translate(language, "discoverSelected");
  return language === "en" && category.description_en ? category.description_en : category.description;
}

export function localizedProductName(product: Product, language: Language): string {
  return language === "en" && product.name_en ? product.name_en : product.name;
}

export function localizedProductDescription(product: Product, language: Language): string {
  return language === "en" && product.description_en ? product.description_en : product.description;
}

export function localizedVariantName(variant: ProductVariant | null | undefined, language: Language): string {
  if (!variant) return "";
  return language === "en" && variant.name_en ? variant.name_en : variant.name;
}
